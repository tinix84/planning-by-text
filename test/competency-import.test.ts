import { writeXlsx } from "../src/xlsx.ts";

test("matrix CLI imports clean headers, minimums and named assessments into a separate file", async () => {
  const dir = mkdtempSync(join(tmpdir(), "pbt-competency-")), plan = join(dir, "plan");
  mkdirSync(plan);
  const original = 'person @alice "Alice Example" role:HW\nperson @bob "Bob Example" role:HW\nproject +ALPHA 2024-01\n+ALPHA.design ~164h ?HW profile:Senior_HW\n@alice +ALPHA.design 100%\n';
  writeFileSync(join(plan, "registry.pbt"), original);
  const wb = new ExcelJS.Workbook(), ws = wb.addWorksheet("Fähigkeitsmatrix_new");
  ws.addRow([null, null, null, "Circuit design: expert metadata", "Review: expert metadata"]);
  ws.addRow([null, "AVG", null, 3, 2]);
  ws.addRow(["ROLE", "Senior HW", null, 3, 2]);
  ws.addRow([null, null, null, "Technical", "Process"]);
  ws.addRow(["Role", "Name", "active", "Circuit design", "Review"]);
  ws.addRow(["INT", "Alice Example", 1, 4, 0]);
  ws.addRow(["EXT", "Robert Example", 0, 3, 2]);
  const matrix = join(dir, "matrix.xlsx");
  await wb.xlsx.writeFile(matrix);
  const bytes = readFileSync(matrix);
  const aliases = join(dir, "aliases.json");
  writeFileSync(aliases, JSON.stringify({ bob: "Robert Example" }));
  const output = join(plan, "competencies.pbt");
  const args = ["tools/import-competencies.ts", matrix, plan, "-o", output, "--aliases", aliases];
  const imported = spawnSync(process.execPath, args, { encoding: "utf8" });
  assert.equal(imported.status, 0, imported.stderr);
  const text = readFileSync(output, "utf8");
  assert.match(text, /competency Circuit_design "Circuit design"/);
  assert.doesNotMatch(text, /expert metadata|AVG|person @/);
  assert.match(text, /assessment @bob active:false/);
  assert.equal(readFileSync(join(plan, "registry.pbt"), "utf8"), original);
  assert.deepEqual(readFileSync(matrix), bytes);
  const { model, diagnostics } = compile(readPlan(plan));
  assert.deepEqual(diagnostics.filter((d) => d.level === "error"), []);
  assert.equal(profileRows(model, "Senior_HW")[0].coverage, 0.5);
  assert.match(renderReport(model, diagnostics), /<th>Profile<\/th>/);
  assert.match(renderReport(model, diagnostics), /<td class="mono">Senior_HW<\/td>/);
  const exported = join(dir, "profile-report.xlsx");
  await writeXlsx(model, diagnostics, exported);
  const exportedWb = new ExcelJS.Workbook();
  await exportedWb.xlsx.readFile(exported);
  assert.equal(exportedWb.getWorksheet("Tasks")!.getRow(3).getCell(10).value, "Senior_HW");
  const matched = spawnSync(process.execPath, ["src/cli.ts", "match", plan, "--task", "ALPHA.design"], { encoding: "utf8" });
  assert.equal(matched.status, 0, matched.stderr);
  assert.equal(JSON.parse(matched.stdout)[0].checks[1].status, "unknown");
  assert.equal(spawnSync(process.execPath, ["src/cli.ts", "match", plan, "--profile", "Typo"]).status, 2);
  const repeated = spawnSync(process.execPath, args, { encoding: "utf8" });
  assert.notEqual(repeated.status, 0);
  assert.equal(readFileSync(output, "utf8"), text);
});

test("ambiguous names remain unassessed and unrelated date errors stay visible", async () => {
  const dir = mkdtempSync(join(tmpdir(), "pbt-competency-identity-")), plan = join(dir, "plan");
  mkdirSync(plan);
  writeFileSync(join(plan, "plan.pbt"), `person @alice "Alice Example"\nproject +ALPHA\n@alice +ALPHA 100% 2024-02-30`);
  const wb = new ExcelJS.Workbook(), ws = wb.addWorksheet("Fähigkeitsmatrix_new");
  ws.addRow(["ROLE", "Senior HW", null, 2]);
  ws.addRow(["Role", "Name", "active", "Circuit\ndesign"]);
  ws.addRow(["INT", "Alice Example", 1, 3]);
  ws.addRow(["INT", "Alice Example", 0, 1]);
  const matrix = join(dir, "matrix.xlsx");
  await wb.xlsx.writeFile(matrix);
  const result = await convertCompetencies(matrix, plan);
  assert.equal(result.matched, 0);
  assert.deepEqual(result.unmatched, ["alice"]);
  assert.equal(result.dateErrors, 1);
  assert.match(result.text, /competency Circuit_design "Circuit design"/);
  assert.doesNotMatch(result.text, /^assessment /m);
  await assert.rejects(convertCompetencies(matrix, plan, { alice: "Alice Example" }), /one exact matrix name/);
  await assert.rejects(convertCompetencies(matrix, plan, { unknown: "Alice Example" }), /Invalid person alias/);
  ws.getRow(4).getCell(2).value = "Other Example";
  ws.getRow(3).getCell(4).value = 5;
  await wb.xlsx.writeFile(matrix);
  await assert.rejects(convertCompetencies(matrix, plan), /level from 0 to 4/);
  ws.getRow(3).getCell(4).value = 3;
  ws.getRow(4).getCell(4).value = -1;
  await wb.xlsx.writeFile(matrix);
  await assert.rejects(convertCompetencies(matrix, plan), /level from 0 to 4/);
  ws.getRow(4).getCell(4).value = 1;
  ws.getRow(2).getCell(5).value = "Circuit design";
  await wb.xlsx.writeFile(matrix);
  await assert.rejects(convertCompetencies(matrix, plan), /colliding competency/);
});
